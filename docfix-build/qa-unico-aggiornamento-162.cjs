'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=__dirname,read=p=>fs.readFileSync(path.join(root,p),'utf8');
const main=read('main.js'),ui=read('app/stability.js'),preload=read('preload.js');
const workflow=fs.readFileSync(path.join(root,'..','.github/workflows/docfix-release-162-collaudo.yml'),'utf8');
assert.ok(main.includes("const UPDATE_API='https://api.github.com/repos/Jorrob98/PDF-Facile/releases/latest'"));
assert.ok(!main.includes('UPDATE_TEST_API'),'no test channel');
assert.ok(!ui.includes('Versioni di prova')&&!ui.includes('Aggiornamenti stabili'),'no user channels');
assert.ok(ui.includes("update.textContent='↻ Verifica aggiornamenti'"),'one check/update button');
assert.ok(ui.includes('window.DocFixUpdater.install()'),'install from inside app');
assert.ok(preload.includes('docfix:update:install'),'IPC update bridge');
assert.ok(main.includes("crypto.createHash('sha256').update(exe)"),'integrity must be checked');
assert.ok(main.includes('writeUpdateReceipt(r.latest)'),'version receipt');
assert.ok(workflow.includes('tag="v${version}"'),'publish numeric tag without RC suffix');
assert.ok(!workflow.includes('--prerelease')&&!workflow.includes('-rc1'),'no alternate release category');
assert.ok(workflow.includes('--latest'),'set update as latest');
assert.ok(workflow.includes('gh api repos/Jorrob98/PDF-Facile/releases/latest'),'verify what installed apps will see');
assert.ok(workflow.includes('sha256sum -c "$shafile"'),'verify executable prior to release');
console.log('PASS: one in-app update, numeric release, complete files, verified latest and SHA-256');
