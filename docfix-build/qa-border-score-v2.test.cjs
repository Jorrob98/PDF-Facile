'use strict';
const assert=require('node:assert/strict');
const {area,valid,intersectionArea,compare,score}=require('./qa-border-score-v2.cjs');
const rect=(x0,y0,x1,y1)=>[{x:x0,y:y0},{x:x1,y:y0},{x:x1,y:y1},{x:x0,y:y1}];
const truth=rect(.1,.15,.9,.8);
assert.ok(valid(truth));
assert.equal(valid([truth[0],truth[2],truth[1],truth[3]]),false);
assert.equal(intersectionArea(truth,truth),area(truth));
assert.ok(compare(truth,truth).iou>.99999);
assert.ok(compare(truth,rect(.11,.15,.89,.8)).coverage<.995);
const refs=[{id:'single',quads:[truth]},{id:'double',quads:[rect(.05,.1,.45,.5),rect(.55,.1,.95,.5)]},{id:'ambiguous',quads:[rect(.15,.2,.85,.75)]}];
const guesses=[{id:'single',quads:[truth],statuses:['auto']},{id:'double',quads:[rect(.05,.1,.45,.5),rect(.55,.1,.95,.5)],statuses:['auto','auto']},{id:'ambiguous',quads:[rect(.18,.2,.85,.75)],statuses:['review']}];
const result=score(refs,guesses);
assert.equal(result.summary.expectedDocuments,4);
assert.equal(result.summary.accepted,3);
assert.equal(result.summary.unsafeAuto,0);
guesses[2].statuses=['auto'];
assert.equal(score(refs,guesses).summary.unsafeAuto,1);
assert.equal(score(refs.slice(0,1),[{id:'single',quads:[],statuses:[]}]).summary.missing,1);
console.log('PASS DocFix Bordi v2: 4 corners, intersections, 1/2 documents, no silent cuts, missing pages');
